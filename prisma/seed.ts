async function main() {
  console.log("🌱 Starting DevAtlas database seed...");

  // 1. Seed Categories
  console.log("-> Seeding categories...");
  const categoryMap = new Map<string, string>();
  for (const cat of CATEGORIES) {
    const record = await prisma.category.upsert({
      where: { slug: cat.slug },
      update: {
        name: cat.name,
        description: cat.description,
        icon: cat.icon,
        order: cat.order,
      },
      create: cat,
    });
    categoryMap.set(cat.slug, record.id);
  }

  // 2. Seed Countries
  console.log("-> Seeding countries...");
  const countryMap = new Map<string, string>();
  for (const c of COUNTRIES) {
    const record = await prisma.country.upsert({
      where: { code: c.code },
      update: {
        name: c.name,
        region: c.region,
      },
      create: c,
    });
    countryMap.set(c.code, record.id);
  }

  // 3. Seed Tags
  console.log("-> Seeding tags...");
  const tagMap = new Map<string, string>();
  for (const t of TAGS) {
    const record = await prisma.tag.upsert({
      where: { slug: t },
      update: { name: t },
      create: { name: t, slug: t },
    });
    tagMap.set(t, record.id);
  }

  // 4. Seed Tools (Pass 1: create or update tools without parentToolId to avoid ordering issues)
  console.log("-> Seeding tools (Pass 1)...");
  const toolMap = new Map<string, string>();

  for (const tool of TOOLS) {
    const categoryId = categoryMap.get(tool.categorySlug);
    if (!categoryId) {
      throw new Error(`Category not found for slug: ${tool.categorySlug}`);
    }

    const countryId = tool.countryCode ? countryMap.get(tool.countryCode) : null;

    // Connect valid tags
    const validTags = tool.tags
      .filter((tag) => tagMap.has(tag))
      .map((tag) => ({ slug: tag }));

    const record = await prisma.tool.upsert({
      where: { slug: tool.slug },
      update: {
        name: tool.name,
        tagline: tool.tagline,
        description: tool.description,
        websiteUrl: tool.websiteUrl,
        docsUrl: tool.docsUrl || null,
        githubUrl: tool.githubUrl || null,
        license: tool.license,
        pricing: tool.pricing,
        createdYear: tool.createdYear,
        popularity: tool.popularity,
        hiddenGem: tool.hiddenGem,
        hiddenGemReason: tool.hiddenGemReason || null,
        isFeatured: tool.isFeatured || false,
        categoryId,
        countryId: countryId || null,
        tags: {
          set: validTags,
        },
      },
      create: {
        name: tool.name,
        slug: tool.slug,
        tagline: tool.tagline,
        description: tool.description,
        websiteUrl: tool.websiteUrl,
        docsUrl: tool.docsUrl || null,
        githubUrl: tool.githubUrl || null,
        license: tool.license,
        pricing: tool.pricing,
        createdYear: tool.createdYear,
        popularity: tool.popularity,
        hiddenGem: tool.hiddenGem,
        hiddenGemReason: tool.hiddenGemReason || null,
        isFeatured: tool.isFeatured || false,
        categoryId,
        countryId: countryId || null,
        tags: {
          connect: validTags,
        },
      },
    });

    toolMap.set(tool.slug, record.id);
  }

  // 5. Tool Hierarchy (Pass 2: update parentToolId)
  console.log("-> Linking parent tools (Pass 2)...");
  for (const tool of TOOLS) {
    if (tool.parentSlug && toolMap.has(tool.parentSlug)) {
      const parentId = toolMap.get(tool.parentSlug);
      await prisma.tool.update({
        where: { slug: tool.slug },
        data: {
          parentToolId: parentId,
        },
      });
    }
  }

  // Verify Counts
  const totalTools = await prisma.tool.count();
  const hiddenGemsCount = await prisma.tool.count({ where: { hiddenGem: true } });
  const featuredCount = await prisma.tool.count({ where: { isFeatured: true } });
  const totalCats = await prisma.category.count();
  const totalCountries = await prisma.country.count();
  const totalTags = await prisma.tag.count();

  // Seed default admin and user
  const adminPasswordHash = await bcrypt.hash("admin123", 10);
  const userPasswordHash = await bcrypt.hash("user123", 10);
  await prisma.user.upsert({
    where: { email: "admin@devatlas.com" },
    update: { role: "admin", name: "DevAtlas Admin" },
    create: {
      email: "admin@devatlas.com",
      name: "DevAtlas Admin",
      password: adminPasswordHash,
      role: "admin",
    },
  });
  await prisma.user.upsert({
    where: { email: "user@devatlas.com" },
    update: { role: "user", name: "Tool Submitter" },
    create: {
      email: "user@devatlas.com",
      name: "Tool Submitter",
      password: userPasswordHash,
      role: "user",
    },
  });

  console.log("🎉 Seed finished successfully!");
  console.log(`- Categories: ${totalCats}`);
  console.log(`- Countries:  ${totalCountries}`);
  console.log(`- Tags:       ${totalTags}`);
  console.log(`- Total Tools: ${totalTools}`);
  console.log(`- Hidden Gems: ${hiddenGemsCount}`);
  console.log(`- Featured:   ${featuredCount}`);
  console.log(`- Users:      2 (admin@devatlas.com, user@devatlas.com)`);
}

main()
  .catch((e) => {
    console.error("❌ Seed failed with error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
